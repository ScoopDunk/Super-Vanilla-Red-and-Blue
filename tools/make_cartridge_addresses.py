#!/usr/bin/env python3
"""Writes the lists of link-time checks that keep save files compatible.

A save file holds ROM addresses for the map the game was saved on: its block data,
text pointer table, script and object data, the block data of connected maps, and the
tileset's graphics, block set and collision list. The game does not look them up again
on CONTINUE. So a save only works across builds (and on a cartridge) if all of those
are at the same place. This script reads the symbol files of a build that is known to
match the cartridges and writes one ASSERT per label.

usage: make_cartridge_addresses.py red.sym blue.sym
"""
import re, sys

def load(path):
    out = {}
    for line in open(path):
        parts = line.split()
        if len(parts) == 2 and ':' in parts[0] and not parts[0].startswith(';') and '.' not in parts[1]:
            bank, addr = parts[0].split(':')
            if int(addr, 16) < 0x8000:
                out[parts[1]] = (int(bank, 16), int(addr, 16))
    return out

red, blue = load(sys.argv[1]), load(sys.argv[2])
GROUPS = [
    ('data/maps/cartridge_addresses.asm', re.compile(r'(_Blocks|_Object|_Script|_TextPointers\d?)$'),
     'map block data, object data, scripts and text pointer tables'),
    ('gfx/tileset_cartridge_addresses.asm', re.compile(r'(_GFX|_Block)$'), 'tileset graphics and block sets'),
    ('data/tilesets/collision_cartridge_addresses.asm', re.compile(r'_Coll$'), 'tileset collision lists'),
]
TILESETS = set(re.findall(r'^\ttileset (\w+),', open('data/tilesets/tileset_headers.asm').read(), re.M))
for path, pattern, what in GROUPS:
    labels = sorted((k for k in red if pattern.search(k) and k in blue), key=lambda k: red[k])
    if 'tileset' in path:
        labels = [k for k in labels if k.rsplit('_', 1)[0] in TILESETS]
    if 'maps' in path:
        labels = [k for k in labels if red[k][0] not in (0x19, 0x1A, 0x1B)]
    lines = ['; Generated by tools/make_cartridge_addresses.py. Do not edit.',
             '; Save files point at these (%s), and the game' % what,
             '; trusts those pointers on CONTINUE, so each must stay where the cartridge has it.',
             '; If one of these fails, something in front of the label changed size: put the new',
             '; code or data in another section instead (see layout.link).', '']
    for k in labels:
        r, b = red[k], blue[k]
        if r == b:
            lines.append('\tcartridge_address %s, $%02x, $%04x' % (k, r[0], r[1]))
        else:
            lines += ['IF DEF(_RED)', '\tcartridge_address %s, $%02x, $%04x' % (k, r[0], r[1]), 'ELSE',
                      '\tcartridge_address %s, $%02x, $%04x' % (k, b[0], b[1]), 'ENDC']
    open(path, 'w').write('\n'.join(lines) + '\n')
    print(path, len(labels), 'labels')
